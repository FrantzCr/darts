// Returns all valid checkout routes for the current remaining score,
// filtered to routes that fit within the available dart count.
List<List<String>> getCheckouts(int score, {int dartsLeft = 3}) {
  if (score < 1 || score > 170) return [];
  final routes = kCheckoutRoutes[score] ?? [];
  return routes.where((r) => r.length <= dartsLeft).take(2).toList();
}

/// True if the score appears in the checkout table at all (regardless of darts left).
bool hasAnyCheckout(int score) {
  if (score < 1 || score > 170) return false;
  return kCheckoutRoutes.containsKey(score);
}

({String label, int points, String kind}) formatStep(String s) {
  if (s == 'Bull') return (label: 'Bull', points: 50, kind: 'bull');
  if (s.startsWith('T')) {
    final n = int.parse(s.substring(1));
    return (label: 'T$n', points: n * 3, kind: 'triple');
  }
  if (s.startsWith('D')) {
    final n = int.parse(s.substring(1));
    return (label: 'D$n', points: n * 2, kind: 'double');
  }
  if (s.startsWith('S')) {
    final n = int.parse(s.substring(1));
    return (label: '$n', points: n, kind: 'single');
  }
  return (label: s, points: 0, kind: 'other');
}
